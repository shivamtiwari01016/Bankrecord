import React, { useCallback, useEffect, useState } from 'react'
import { Link } from 'react-router-dom'
import { api, formatMoney, formatDateTime } from '../api.js'
import { Card, Field, Alert, DataTable, Pagination, Badge } from '../components/UI.jsx'

const EMPTY = { holderName: '', accountType: 'SAVINGS', currency: 'INR' }
const PAGE_SIZE = 10

export default function Accounts() {
  const [accounts, setAccounts] = useState(null)
  const [page, setPage] = useState(0)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState(null)
  const [form, setForm] = useState(EMPTY)
  const [busy, setBusy] = useState(false)
  const [notice, setNotice] = useState(null)

  const load = useCallback(async () => {
    setLoading(true)
    try {
      const res = await api.listAccounts({ page, size: PAGE_SIZE })
      setAccounts(res)
      setError(null)
    } catch (e) {
      setError(e.message)
    } finally {
      setLoading(false)
    }
  }, [page])

  useEffect(() => {
    load()
  }, [load])

  const submit = async (e) => {
    e.preventDefault()
    setBusy(true)
    setError(null)
    setNotice(null)
    try {
      const created = await api.createAccount(form)
      setNotice(`Account ${created.accountNumber} created for ${created.holderName}.`)
      setForm(EMPTY)
      setPage(0)
      await load()
    } catch (e2) {
      setError(e2.message)
    } finally {
      setBusy(false)
    }
  }

  return (
    <div className="page">
      <header className="page-head">
        <div>
          <h1>Accounts</h1>
          <p className="muted">Create simulated bank accounts and inspect their balances.</p>
        </div>
      </header>

      <Alert kind="error" onClose={() => setError(null)}>
        {error}
      </Alert>
      <Alert kind="success" onClose={() => setNotice(null)}>
        {notice}
      </Alert>

      <Card title="Create account" subtitle="Account number and opening balance are generated by the backend.">
        <form className="form-row" onSubmit={submit}>
          <Field label="Holder name">
            <input
              required
              maxLength={150}
              value={form.holderName}
              onChange={(e) => setForm({ ...form, holderName: e.target.value })}
              placeholder="e.g. Asha Verma"
            />
          </Field>
          <Field label="Account type">
            <select
              value={form.accountType}
              onChange={(e) => setForm({ ...form, accountType: e.target.value })}
            >
              <option>SAVINGS</option>
              <option>CURRENT</option>
              <option>SALARY</option>
            </select>
          </Field>
          <Field label="Currency">
            <select
              value={form.currency}
              onChange={(e) => setForm({ ...form, currency: e.target.value })}
            >
              <option>INR</option>
              <option>USD</option>
              <option>EUR</option>
              <option>GBP</option>
            </select>
          </Field>
          <button className="btn btn-primary" disabled={busy}>
            {busy ? 'Creating…' : 'Create account'}
          </button>
        </form>
      </Card>

      <Card title="All accounts" subtitle={`${accounts?.totalElements ?? 0} account(s)`}>
        <DataTable
          loading={loading}
          columns={['Account No.', 'Holder', 'Type', 'Currency', 'Balance', 'Status', 'Created']}
          rows={accounts?.content}
          empty="No accounts yet — create one above."
          renderRow={(a) => (
            <tr key={a.id}>
              <td>
                <Link to={`/accounts/${a.id}`} className="link mono">
                  {a.accountNumber}
                </Link>
              </td>
              <td>{a.holderName}</td>
              <td>
                <Badge>{a.accountType}</Badge>
              </td>
              <td>{a.currency}</td>
              <td className="num">{formatMoney(a.balance, a.currency)}</td>
              <td>
                <Badge>{a.status}</Badge>
              </td>
              <td className="muted small">{formatDateTime(a.createdAt)}</td>
            </tr>
          )}
        />
        <Pagination
          page={page}
          totalPages={accounts?.totalPages}
          totalElements={accounts?.totalElements}
          onChange={setPage}
        />
      </Card>
    </div>
  )
}
